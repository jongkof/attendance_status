--   이 자료는 월력요항이 공식 발표되기 전 자료다.
-- - 2029–2030년: 월력요항이 아직 공개되지 않았다. 음력 날짜는 한국천문연구원 음양력 변환 자료에 기반한
--   korean-lunar-calendar 패키지로 계산하고(2028년 값은 위 월력요항과 일치), 공휴일 정리 자료와 대조했다.
--   대체공휴일은 공휴일에 관한 법률 기준(설날·추석 연휴와 어린이날, 부처님오신날 등이 일요일이나 다른 공휴일과 겹치면,
--   어린이날은 토요일과도 겹치면 다음 첫 비공휴일)으로 계산했다.
-- - 제헌절은 2026–2027년 데이터와 같이 휴일로 넣었다. 월력요항 2028년 자료는 제헌절을 공휴일이 아닌 국경일로 적고 있다.
-- - 넣지 않은 것: 2030년 지방선거일(6/5와 6/12 중 어느 쪽인지 공식 자료로 확인하지 못함),
--   2030년 대통령선거일(날짜 확인 못함), 임시공휴일 전부. 확인되면 달력 편집 화면에서 등록한다.
